def remapping_ids(df):
    user_ids  = sorted(df["userId"].unique())
    movie_ids = sorted(df["movieId"].unique())

    user_to_idx  = {uid: i for i, uid in enumerate(user_ids)}
    movie_to_idx = {mid: i for i, mid in enumerate(movie_ids)}
    df = df.copy()
    df["user_idx"]  = df["userId"].map(user_to_idx)
    df["movie_idx"] = df["movieId"].map(movie_to_idx)
    return df, user_to_idx, movie_to_idx

#Build the networkX graph function
def build_nx_graph(df):
    G = nx.Graph()
    for _, row in df.iterrows():
        #Access movie data
        user_node  = f"user_{int(row['user_idx'])}"
        movie_node = f"movie_{int(row['movie_idx'])}"
        G.add_node(user_node,  node_type="user")
        G.add_node(movie_node, node_type="movie")
        G.add_edge(user_node, movie_node, weight=row["rating"])
    return G

#Build the PyTorch Geometric graph
def build_pyg_graph(df, num_users, num_movies):
    #Convert data to tensors
    user_idx  = torch.tensor(df["user_idx"].values,dtype=torch.long)
    movie_idx = torch.tensor(df["movie_idx"].values + num_users,  dtype=torch.long)

    #Building undirected graph and add edges in both directions
    edge_index = torch.stack([
        torch.cat([user_idx,  movie_idx]),
        torch.cat([movie_idx, user_idx]),
    ], dim=0)
    return edge_index


# Global Bipartite graph - which shows the bipartite graph for full dataset by selecting the top 20 users and top 30 movies
def visualize_global_bipartite_graph(G, top_n_users=20, top_n_movies=30, save_path="bipartite_graph_global.png"):
    user_nodes  = [n for n, d in G.nodes(data=True) if d.get("node_type") == "user"]
    movie_nodes = [n for n, d in G.nodes(data=True) if d.get("node_type") == "movie"]

    # Sort users and movies by degree
    user_degrees  = sorted(user_nodes,  key=lambda n: G.degree(n), reverse=True)
    movie_degrees = sorted(movie_nodes, key=lambda n: G.degree(n), reverse=True)

    # Select the top 20 users and top 30 movies
    selected_users  = user_degrees[:top_n_users]
    selected_movies = movie_degrees[:top_n_movies]

    sub_nodes = set(selected_users) | set(selected_movies)
    H = G.subgraph(sub_nodes)

    # Visualize graph as users on left and movies on right
    pos = {}
    for i, node in enumerate(selected_users):
        pos[node] = (0, i * 2)
    for i, node in enumerate(selected_movies):
        pos[node] = (6, i * (len(selected_users) * 2 / max(len(selected_movies), 1)))

    node_colors, node_sizes = [], []
    for node in H.nodes():
        if H.nodes[node].get("node_type") == "user":
            node_colors.append("#4A90D9")   # blue for users
            node_sizes.append(500)
        else:
            node_colors.append("#2ECC71")   # green for movies
            node_sizes.append(400)

    edge_weights = [H[u][v].get("weight", 1) for u, v in H.edges()]
    max_w = max(edge_weights) if edge_weights else 1
    edge_widths = [0.3 + 1.5 * (w / max_w) for w in edge_weights]

    fig, ax = plt.subplots(figsize=(18, 10))
    fig.patch.set_facecolor("#1A1A2E")
    ax.set_facecolor("#1A1A2E")

    nx.draw_networkx_edges(H, pos, width=edge_widths, edge_color="#888888", alpha=0.4, ax=ax)
    nx.draw_networkx_nodes(H, pos, node_color=node_colors, node_size=node_sizes, alpha=0.95, ax=ax)

    labels = {}
    for node in H.nodes():
        if H.nodes[node].get("node_type") == "movie":
            labels[node] = node.replace("movie_", "M")
        else:
            labels[node] = node.replace("user_", "U")
    nx.draw_networkx_labels(H, pos, labels, font_size=6, font_color="white", ax=ax)

    total_users  = len(user_nodes)
    total_movies = len(movie_nodes)
    total_edges  = G.number_of_edges()
    stats_text   = (f"Total Users: {total_users}   |   "
                    f"Total Movies: {total_movies}   |   "
                    f"Total Interactions: {total_edges}")
    ax.text(0.5, -0.02, stats_text, transform=ax.transAxes, ha="center", va="top", color="#AAAAAA", fontsize=9)

    legend_handles = [
        mpatches.Patch(color="#4A90D9", label=f"Users (showing {len(selected_users)} of {total_users})"),
        mpatches.Patch(color="#2ECC71", label=f"Movies (showing {len(selected_movies)} of {total_movies})"),
    ]
    ax.legend(handles=legend_handles, loc="upper right",
              facecolor="#2D2D44", edgecolor="none", labelcolor="white", fontsize=9)

    ax.set_title("Global User–Movie Bipartite Graph (Overview)",
                 color="white", fontsize=15, pad=14)
    ax.axis("off")
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight",
                facecolor=fig.get_facecolor())
    plt.show()
    print(f"[INFO] Global graph saved to {save_path}")

